check('ontkoppelen maakt twee los', r.n1 === 2); check('stil: niemand neemt hem over', r.stilBlijft === 0);
check('tweede keer breekt hem af', r.sloop === 1 && r.weg && r.stand.n === 0, JSON.stringify(r.stand));
