// Stap 40: Broeder Ludolf zit in een cel op het binnenplein van rood (level 5) en komt vrij als de burcht valt.
import { chromium } from '/home/claude/.npm-global/lib/node_modules/playwright/index.mjs';
import { spawn } from 'child_process';
const srv = spawn('python3', ['-m', 'http.server', '8286'], { cwd: '/home/claude/burcht-en-banier', stdio: 'ignore' });
await new Promise((r) => setTimeout(r, 800));
const b = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox'] });
const p = await (await b.newContext({ viewport: { width: 844, height: 390 } })).newPage();
const fouten = []; p.on('pageerror', (e) => fouten.push(String(e))); p.on('console', (m) => { if (m.type() === 'error' && !/404/.test(m.text())) fouten.push(m.text()); });   // 404: de verhaalbeelden van 0.51.0 ontbreken nog
let ok = 0, fout = 0;
const check = (n, w, x = '') => { if (w) ok++; else { fout++; console.log('FOUT:', n, x); } };
const wacht = () => p.waitForFunction(() => window.spel && window.spel.strijd, null, { timeout: 20000 });
const start = async (missie) => {
  await p.goto('http://localhost:8286/?x=' + Date.now()); await wacht();
  await p.evaluate((m) => { localStorage.clear(); localStorage.setItem('burcht-banier.campagne', JSON.stringify({ klaar: [0, 1, 2, 3, 4] })); localStorage.setItem('burcht-banier.modus', JSON.stringify({ soort: 'campagne', missie: m })); sessionStorage.setItem('burcht-banier.geenTitel', '1'); }, missie);
  await p.reload(); await wacht(); await p.waitForTimeout(300);
};
const cel = () => p.evaluate(() => { const k = window.spel.kaart; const r = []; for (let i = 0; i < k.breedte * k.hoogte; i++) if (k.object[i] === 30 || k.object[i] === 31) r.push([i % k.breedte, Math.floor(i / k.breedte), k.object[i]]); return { r, rood: k.start[1] }; });
await start(5);
let c = await cel();
check('level 5: precies een cel', c.r.length === 1 && c.r[0][2] === 30, JSON.stringify(c));
check('de cel staat binnen 4 tegels van het rode kasteel', c.r.length === 1 && Math.max(Math.abs(c.r[0][0] - c.rood.x), Math.abs(c.r[0][1] - c.rood.y)) <= 4, JSON.stringify(c));
check('de cel is een tegel waar je niet door loopt', await p.evaluate((r) => !window.spel.wegvinder.isVrij(r[0], r[1], 1), c.r[0]));
const nodig = await p.evaluate(() => ['dorp.cel', 'dorp.cel_open'].every((n) => window.spel.assets ? window.spel.assets.heeft(n) : true));
check('beide plaatjes bestaan', nodig);
await p.evaluate(() => { const s = window.spel; s.strijd.pauzeer(true); });
await p.screenshot({ path: '/tmp/cel-dicht.png' });
await start(1);
c = await cel();
check('level 1: geen cel', c.r.length === 0, JSON.stringify(c));
await start(5);
await p.evaluate(() => { const s = window.spel; s.strijd.pauzeer(false); });
await p.evaluate(() => { const s = window.spel; for (let i = 0; i < 40; i++) { const k = s.strijd.roodKoning(); if (k) { k.leven = 0; k.dood = true; } s.eenheden.stap(0.1); s.leger.stap(); s.strijd.stap(); if (s.strijd.uitslag()) break; } });
const u = await p.evaluate(() => window.spel.strijd.uitslag());
check('de rode heer valt: gewonnen', u === 'gewonnen', u);
c = await cel();
check('na de winst staat de cel open', c.r.length === 1 && c.r[0][2] === 31, JSON.stringify(c));
await p.screenshot({ path: '/tmp/cel-open.png' });
check('geen paginafouten', fouten.length === 0, fouten.join('|'));
console.log('cel40:', ok, 'goed,', fout, 'fout');
await b.close(); srv.kill();
